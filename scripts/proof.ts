/**
 * Reproducible proof run: evaluates the real dataset for a baseline and two
 * hypothetical swimming-facility locations, and prints a Markdown report.
 *
 *   npm run proof            # prints to stdout
 *   npm run proof > docs/PROOF_RUN_OUTPUT.md
 */
import { candidateSites, dataset, evaluationPoints } from "../src/lib/data";
import { formatDelta, formatMeters } from "../src/lib/insights";
import { activeFacilities, evaluateScenario, suggestSites, type ScenarioResult } from "../src/lib/scenario";
import type { HypotheticalFacility } from "../src/lib/types";

const hyp = (lat: number, lon: number): HypotheticalFacility[] => [
  { id: "hyp-1", lat, lon, category: "swimming", label: "Varsayımsal yüzme tesisi 1" },
];
const run = (h: HypotheticalFacility[], scope: "core" | "all" = "core") =>
  evaluateScenario({ points: evaluationPoints, facilities: dataset.facilities, category: "swimming", scope, hypotheticals: h, thresholdM: 1000 });

// Location A: east of the corridor (Gazipaşa area); Location B: west (İsmetpaşa area).
const A_POS = { lat: 37.0105, lon: 35.3205 };
const B_POS = { lat: 37.008, lon: 35.285 };
const base = run([]);
const A = run(hyp(A_POS.lat, A_POS.lon));
const B = run(hyp(B_POS.lat, B_POS.lon));
const best = suggestSites(evaluationPoints, dataset.facilities, "swimming", "core", 1000, 3, candidateSites);

const row = (label: string, r: ScenarioResult) =>
  `| ${label} | ${r.after.withinCount} / ${r.after.pointCount} | ${formatMeters(r.after.meanM)} | ${formatMeters(r.after.medianM)} | ${formatMeters(r.after.maxM)} | ${r.change.pointsImproved} | ${r.canalBelt.after.withinCount} / ${r.canalBelt.after.pointCount} |`;

const out: string[] = [];
out.push("# KanalAtlas proof run (generated)");
out.push("");
out.push(`Generated by \`npm run proof\` at ${new Date().toISOString()} from \`src/data/kanalatlas-data.json\` (OSM extract ${dataset.extractedAt}).`);
out.push("Category: swimming · scope: core (named/tagged) · threshold: 1 km straight-line · 72 grid points (500 m).");
out.push("");
out.push(`Facilities in analysis: ${activeFacilities(dataset.facilities, "swimming", "core").map((f) => `${f.name ?? "unnamed"} (${f.sources.map((s) => `${s.osmType}/${s.osmId}`).join("+")})`).join("; ")}`);
out.push("");
out.push("| Scenario | Points ≤ 1 km | Mean | Median | Max | Points improved | Canal-belt ≤ 1 km |");
out.push("|---|---|---|---|---|---|---|");
out.push(row("Baseline (no hypothetical)", base));
out.push(row(`A: hypothetical at ${A_POS.lat}, ${A_POS.lon}`, A));
out.push(row(`B: hypothetical at ${B_POS.lat}, ${B_POS.lon}`, B));
out.push("");
out.push(`Sensitivity: with scope = all (unnamed pools included) the baseline is ${run([], "all").after.withinCount} / 72 within 1 km.`);
out.push("");
out.push("Best single site screened over the 100 m candidate grid (" + candidateSites.length + " candidates):");
for (const s of best) out.push(`- ${s.lat.toFixed(5)}, ${s.lon.toFixed(5)} (${s.nearLabel ?? "—"}): +${s.withinGained} points within 1 km`);
out.push("");
out.push("Per-point changes for A and B (only points whose distance changed):");
out.push("");
out.push("| Point | Near (approx.) | Before | After A | Δ A | After B | Δ B |");
out.push("|---|---|---|---|---|---|---|");
evaluationPoints.forEach((p, i) => {
  const a = A.points[i];
  const b = B.points[i];
  if ((a.deltaM ?? 0) === 0 && (b.deltaM ?? 0) === 0) return;
  out.push(
    `| ${p.id} | ${p.nearLabel ?? "—"} | ${formatMeters(base.points[i].before?.distanceM)} | ${formatMeters(a.after?.distanceM)} | ${formatDelta(a.deltaM)} | ${formatMeters(b.after?.distanceM)} | ${formatDelta(b.deltaM)} |`,
  );
});
console.log(out.join("\n"));
